import { Command } from 'commander';
import * as p from '@clack/prompts';
import fs from 'fs';
import path from 'path';
import pc from 'picocolors';

export const cmsCommand = new Command('sync-cms')
  .description('Sync CMS schema (ACF/Gutenberg) to React components')
  .action(async () => {
    p.intro(pc.bgMagenta(pc.black(' Ecom-os CMS Sync ')));

    const project = await p.group(
      {
        endpoint: () =>
          p.text({
            message: 'WordPress REST API endpoint?',
            initialValue: 'http://localhost:8000/wp-json/epioso/v1/schema',
            validate: (value) => {
              if (!value) return 'Endpoint is required';
              try {
                new URL(value);
              } catch (e) {
                return 'Invalid URL';
              }
            },
          }),
      },
      {
        onCancel: () => {
          p.cancel('Operation cancelled.');
          process.exit(0);
        },
      }
    );

    const s = p.spinner();
    s.start('Fetching schema from WordPress...');

    try {
      // In a real scenario we'd do:
      // const res = await fetch(project.endpoint);
      // const schema = await res.json();
      
      // For now, simulate fetching a schema payload
      await new Promise(r => setTimeout(r, 1000));
      
      const mockSchema = {
        blocks: [
          {
            name: 'epioso/hero',
            attributes: {
              title: { type: 'string' },
              subtitle: { type: 'string' },
              backgroundImageUrl: { type: 'string' }
            }
          },
          {
            name: 'epioso/feature-grid',
            attributes: {
              heading: { type: 'string' },
              columns: { type: 'number' }
            }
          }
        ]
      };

      s.message('Generating TypeScript interfaces...');

      // Generate interfaces
      let tsOutput = `// AUTO-GENERATED BY ECOM-OS CLI - DO NOT EDIT\n\n`;
      
      mockSchema.blocks.forEach(block => {
        const interfaceName = block.name.replace('epioso/', '').split('-').map(s => s.charAt(0).toUpperCase() + s.slice(1)).join('') + 'BlockProps';
        
        tsOutput += `export interface ${interfaceName} {\n`;
        for (const [attrName, attrData] of Object.entries(block.attributes)) {
          tsOutput += `  ${attrName}: ${attrData.type};\n`;
        }
        tsOutput += `}\n\n`;
      });

      const typesPath = path.join(process.cwd(), '../../packages/ecom-engine/src/cms.ts');
      // Ensure directory exists
      fs.mkdirSync(path.dirname(typesPath), { recursive: true });
      fs.writeFileSync(typesPath, tsOutput);

      s.stop('Done');

      p.note(
        `Generated interfaces in: packages/ecom-engine/src/cms.ts\nGenerated 2 block definitions.`,
        'Sync successful!'
      );

      p.outro(pc.green('React components are now strongly typed against your CMS!'));
    } catch (err: any) {
      s.stop('Failed');
      p.log.error(pc.red(`Failed to fetch or generate schema: ${err.message}`));
      process.exit(1);
    }
  });
