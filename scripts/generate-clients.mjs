#!/usr/bin/env node
// Generate the client profile and theme registries from the folders on disk, so
// adding a client means adding files, not editing core registries.
//   clients/<id>/profile.ts                 -> apps/storefront/src/clients.generated.ts
//   packages/themes/src/clients/<id>/theme.ts -> packages/themes/src/registry.generated.ts
// Usage: node scripts/generate-clients.mjs [--check]   (--check fails if files are stale)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HEADER = '// Generated by scripts/generate-clients.mjs. Do not edit by hand.\n';

/** Find folders `<dir>/<id>/<file>` and the single `export const <name><suffix>` in each. */
export function discover(baseDir, file, suffix) {
  if (!fs.existsSync(baseDir)) return [];
  const found = [];
  for (const entry of fs.readdirSync(baseDir, { withFileTypes: true })) {
    if (!entry.isDirectory()) continue;
    const filePath = path.join(baseDir, entry.name, file);
    if (!fs.existsSync(filePath)) continue;
    const source = fs.readFileSync(filePath, 'utf8');
    const names = [...source.matchAll(new RegExp(`export const (\\w+${suffix})\\b`, 'g'))].map((m) => m[1]);
    if (names.length !== 1) {
      throw new Error(
        `${path.relative(process.cwd(), filePath)} must export exactly one "<name>${suffix}" constant, found ${names.length}.`
      );
    }
    found.push({ id: entry.name, exportName: names[0] });
  }
  const sorted = found.sort((a, b) => a.id.localeCompare(b.id));
  const seen = new Map();
  for (const item of sorted) {
    if (seen.has(item.exportName)) {
      throw new Error(`Export name "${item.exportName}" is used by both "${seen.get(item.exportName)}" and "${item.id}".`);
    }
    seen.set(item.exportName, item.id);
  }
  return sorted;
}

const key = (id) => (/^[A-Za-z_$][\w$]*$/.test(id) ? id : JSON.stringify(id));

export function renderProfiles(items) {
  const imports = items.map((i) => `import { ${i.exportName} } from '../../../clients/${i.id}/profile';`).join('\n');
  const body = items.map((i) => `  ${key(i.id)}: ${i.exportName},`).join('\n');
  return `${HEADER}import type { ClientProfile } from '@ecom-os/brand-config';\n${imports}\n\nexport const generatedProfiles: Record<string, ClientProfile> = {\n${body}\n};\n`;
}

export function renderThemes(items) {
  const imports = items.map((i) => `import { ${i.exportName} } from './clients/${i.id}/theme';`).join('\n');
  const body = items.map((i) => `  ${key(i.id)}: ${i.exportName},`).join('\n');
  return `${HEADER}import type { EcomTheme } from './types';\n${imports}\n\nexport const generatedThemes: Record<string, EcomTheme> = {\n${body}\n};\n`;
}

export function generate(rootDir) {
  const profiles = discover(path.join(rootDir, 'clients'), 'profile.ts', 'Profile');
  const themes = discover(path.join(rootDir, 'packages/themes/src/clients'), 'theme.ts', 'Theme');
  return [
    { file: path.join(rootDir, 'apps/storefront/src/clients.generated.ts'), content: renderProfiles(profiles), count: profiles.length },
    { file: path.join(rootDir, 'packages/themes/src/registry.generated.ts'), content: renderThemes(themes), count: themes.length },
  ];
}

const normalize = (text) => text.replace(/\r\n/g, '\n');

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const rootDir = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const check = process.argv.includes('--check');
  try {
    const outputs = generate(rootDir);
    let stale = 0;
    for (const out of outputs) {
      const current = fs.existsSync(out.file) ? normalize(fs.readFileSync(out.file, 'utf8')) : null;
      if (check) {
        if (current !== out.content) {
          stale++;
          console.error(`Stale: ${path.relative(rootDir, out.file)} (run: node scripts/generate-clients.mjs)`);
        }
      } else if (current !== out.content) {
        fs.writeFileSync(out.file, out.content);
        console.log(`Generated ${path.relative(rootDir, out.file)} (${out.count} entries)`);
      }
    }
    if (check && stale) process.exit(1);
    if (check) console.log('Client registries are up to date.');
  } catch (err) {
    console.error(`Error generating client registries: ${err.message}`);
    process.exit(1);
  }
}
